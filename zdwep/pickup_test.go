package zdwep

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// A weapon lying on the floor and the box of ammo beside it are both drawn
// from the frame the actor's Spawn state starts on, and both go into the
// shared picture store rather than the weapon's own atlas - what draws them is
// a pickup, an inventory list and the HUD, none of which have the weapon in
// hand.
//
// The awkward part is which ammo. A weapon names up to two pools and DECORATE
// says nothing about which is the loaded magazine and which the reserve; the
// mod below has them in the order the Dual 92s do, magazine first, which is
// the order that reads wrong if you trust the slot.
const pickupMod = `
ACTOR PickupMagazine : Ammo
{
  Inventory.MaxAmount 30
}

ACTOR PickupReserve : Ammo
{
  Inventory.MaxAmount 200
  States
  {
  Spawn:
    PBOX A -1
    Stop
  }
}

ACTOR PickupPistol : Weapon
{
  Weapon.AmmoType1 "PickupMagazine"
  Weapon.AmmoType2 "PickupReserve"
  States
  {
  Spawn:
    TNT1 A 0
    PGUN A -1
    Stop
  Ready:
    PIDL A 1 A_WeaponReady (WRF_ALLOWRELOAD)
    Loop
  Fire:
    PIDL B 2 A_FireBullets (1, 1, 1, 5)
    Goto Ready
  Reload:
    PIDL C 8 A_TakeInventory ("PickupReserve", 30)
    PIDL C 1 A_GiveInventory ("PickupMagazine", 30)
    Goto Ready
  Select:
    PIDL A 1 A_Raise
    Loop
  Deselect:
    PIDL A 1 A_Lower
    Loop
  }
}

ACTOR PickupKnife : Weapon
{
  States
  {
  Ready:
    KNIF A 1 A_WeaponReady
    Loop
  Fire:
    KNIF B 2 A_CustomPunch (10)
    Goto Ready
  Select:
    KNIF A 1 A_Raise
    Loop
  Deselect:
    KNIF A 1 A_Lower
    Loop
  }
}

ACTOR PickupIconGun : Weapon
{
  Inventory.Icon "PWICON"
  States
  {
  Ready:
    IGUN A 1 A_WeaponReady
    Loop
  Fire:
    IGUN B 2 A_FireBullets (1, 1, 1, 5)
    Goto Ready
  Select:
    IGUN A 1 A_Raise
    Loop
  Deselect:
    IGUN A 1 A_Lower
    Loop
  }
}

ACTOR PickupPlayer : DoomPlayer
{
  Player.StartItem "PickupKnife"
  Player.StartItem "PickupPistol"
  Player.StartItem "PickupBullets", 40
}

ACTOR PickupStockGun : Weapon
{
  Weapon.AmmoType "Clip"
  States
  {
  Ready:
    SGUN A 1 A_WeaponReady
    Loop
  Fire:
    SGUN B 2 A_FireBullets (1, 1, 1, 5)
    Goto Ready
  Select:
    SGUN A 1 A_Raise
    Loop
  Deselect:
    SGUN A 1 A_Lower
    Loop
  }
}
`

// What a mod's own TEXTURES lump says PWICON is: a picture built out of a
// sprite it already ships, which is how Final Doomer gives all eighty of its
// weapons an icon without drawing one.
const pickupTextures = `
// generated by SLADE3
Graphic PWICON, 43, 13
{
	XScale 0.500
	YScale 0.500
	Patch PWEPZ0, 0, 0
}
`

func compilePickupWeapon(t *testing.T, name string) *Result {
	t.Helper()
	idx := indexFromFiles(t, map[string]string{
		"DECORATE": pickupMod, "TEXTURES.hud": pickupTextures})
	result, err := CompileWeapon(idx, DefaultPolicy(), name)
	require.NoError(t, err)
	return result
}

func TestPickupIconsComeFromSpawnStates(t *testing.T) {
	result := compilePickupWeapon(t, "PickupPistol")
	weapon := result.Weapon

	// The first frame of Spawn that shows anything: the TNT1 in front of it is
	// not a picture.
	assert.Equal(t, "PGUNA0", weapon.Icon)

	// The magazine is first in the weapon's own properties and has no picture
	// of itself on the floor, because nobody drops a magazine. The reserve is
	// what a box of ammo hands over.
	assert.Equal(t, "PickupReserve", weapon.AmmoPickup)
	assert.Equal(t, "PBOXA0", weapon.AmmoIcon)

	// Both go to the shared store, not to the weapon's own atlas.
	assert.Contains(t, result.ActorSprites, "PGUNA0")
	assert.Contains(t, result.ActorSprites, "PBOXA0")
}

func TestPickupIconFallsBackToTheFirstPersonFrame(t *testing.T) {
	weapon := compilePickupWeapon(t, "PickupKnife").Weapon

	// No Spawn state anywhere in its line - which is most of these mods - so
	// the only picture of the thing is the frame it is held in. That is a
	// stand-in and it is recorded as one.
	assert.Equal(t, "KNIFA0", weapon.Icon)
	assert.Contains(t, weapon.Defaulted, "no pickup sprite, using the first-person frame KNIFA0")

	// Nothing to spend, so there is no box of ammo for it.
	assert.Empty(t, weapon.AmmoPickup)
	assert.Empty(t, weapon.AmmoIcon)
}

func TestPickupIconForDoomsOwnAmmo(t *testing.T) {
	weapon := compilePickupWeapon(t, "PickupStockGun").Weapon

	// Clip is the base game's, defined in no mod's DECORATE, so there is no
	// Spawn state to read and the answer comes from what doom2.wad calls it.
	assert.Equal(t, "Clip", weapon.AmmoPickup)
	assert.Equal(t, "CLIPA0", weapon.AmmoIcon)
}

func TestPickupIconFromInventoryIconThroughTextures(t *testing.T) {
	result := compilePickupWeapon(t, "PickupIconGun")

	// No Spawn state - the weapon is never dropped - so the icon is what the
	// mod named for the status bar, and that is a texture rather than a lump:
	// it only means anything once TEXTURES has been read.
	assert.Equal(t, "PWEPZ0", result.Weapon.Icon)
	assert.Contains(t, result.ActorSprites, "PWEPZ0")

	// It is the mod's own picture of the weapon, not a stand-in, so nothing is
	// recorded as defaulted.
	assert.NotContains(t, result.Weapon.Defaulted, "no pickup sprite, using the first-person frame IGUNA0")
}

func TestPickupStartingWeaponsAreNeverPickups(t *testing.T) {
	// The player class hands these two out before the first frame, so they are
	// never anywhere to be picked up.
	assert.True(t, compilePickupWeapon(t, "PickupKnife").Weapon.Starting)
	assert.True(t, compilePickupWeapon(t, "PickupPistol").Weapon.Starting)

	// Nothing hands this one out.
	assert.False(t, compilePickupWeapon(t, "PickupStockGun").Weapon.Starting)
}

func TestPickupClipIsWhatTheReloadFills(t *testing.T) {
	ammo := compilePickupWeapon(t, "PickupPistol").Weapon.Ammo

	// The magazine and the reserve are both `: Ammo` with a maximum and
	// DECORATE says nothing about which is which. What tells them apart is
	// that a reload fills a magazine.
	assert.Equal(t, "PickupMagazine", ammo.Clip)
	assert.Equal(t, "PickupReserve", ammo.Type2)

	// A weapon that pumps inside its own firing states has no magazine to
	// count down separately from the ammo it spends.
	assert.Empty(t, compilePickupWeapon(t, "PickupStockGun").Weapon.Ammo.Clip)
}
